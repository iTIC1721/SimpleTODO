// Release signing credentials live in keystore.properties at the project root,
// which is gitignored — never commit the keystore or its passwords.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

android {
    namespace = "com.simpletodo.simpletodo"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.simpletodo.simpletodo"
        minSdk = 26
        targetSdk = 37
        versionCode = 4
        versionName = "1.1.1"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        create("release") {
            if (keystoreProperties.isNotEmpty()) {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            optimization {
                enable = false
            }
            // Without keystore.properties the release build is left unsigned
            // rather than failing, so the project still builds on any machine.
            if (keystoreProperties.isNotEmpty()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
    }
}

ksp {
    // Historical schema snapshots, used to verify and auto-generate Room
    // migrations between versions instead of silently wiping data on upgrade.
    arg("room.schemaLocation", "$projectDir/schemas")
}

